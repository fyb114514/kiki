"""
因果 / 属性推理规则(纯本地,不联网)。

用户要的核心能力:
    "知道比尔盖茨是微软(一家大公司)的 CEO 后,能够推断出他很出名"

这类结论**不在事实库里**,必须从已有事实 + 规则推出来。本模块就是那些规则。

设计原则
--------
1. 规则写成**数据**(表),不是散落在 if/else 里 —— 加规则只改表。
2. 每条规则都要能说清"依据"(why),便于回答时解释怎么推出来的。
3. 严格区分"可推出"与"猜":宁可推不出,也不要瞎推(用户明确说过
   "错误答案比不回答更糟")。

三类推理
--------
A. **属性继承**:X 是 Y,Y 是 Z  =>  X 是 Z
      卡卡是猫,猫是哺乳动物 => 卡卡是哺乳动物
B. **逆关系**:X 建立者 Y  =>  Y 由 X 建立
      东吴建立者孙权 => 孙权建立了东吴
C. **因果蕴含**:前提成立 => 结论成立(带置信度)
      X 建立者 Y(且 Y 是朝代)  =>  X 是历史人物
      X 位于 Y                  =>  X 在 Y 境内
"""

from typing import List, Optional, Tuple


# ---------------------------------------------------------------
# A. 属性继承链:能"是"传递的关系
# ---------------------------------------------------------------
# 注意:只放真正可传递的关系。像"首都"就不能传递。
ISA_RELS = ("是", "属于", "又叫", "简称")


# ---------------------------------------------------------------
# B. 逆关系:把单向事实反过来表述
#     正关系 -> (反关系, 反着问时的问法模板)
# ---------------------------------------------------------------
INVERSE_RELS = {
    # 关系: (反着问时的问法, 反转后的说法模板)
    #
    # 中文方向要小心:"由…建立/发明" 的主语是**被建立/被发明的那个东西**。
    #   东吴 建立者 孙权   -> "东吴由孙权建立"  ✅
    #                     -> "孙权由东吴建立"  ❌(第一版就是这个错)
    #   毕昇 发明 活字印刷术 -> "活字印刷术由毕昇发明" ✅
    "建立者": ("由谁建立", "{s}由{o}建立"),
    "创立": ("由谁创立", "{s}由{o}创立"),
    "发明": ("由谁发明", "{o}由{s}发明"),
    "首都": ("是谁的首都", "{o}是{s}的首都"),
    "省会": ("是谁的省会", "{o}是{s}的省会"),
    # "位于"不反转:正着说就是"{s}位于{o}",反转只会得到同一句话(实测重复过),
    # 所以这里不给它逆关系,改由因果规则产出"在…境内"。
}


# ---------------------------------------------------------------
# C. 因果蕴含规则
#     前提(一组 (主语位置, 关系, 宾语位置/约束)) -> 结论(关系, 文本模板)
#     s = 事实主语, o = 事实宾语
# ---------------------------------------------------------------
# 每条: (关系元组列表, 结论关系, 结论文本模板, 依据说明)
CAUSAL_RULES = [
    # 某朝代的建立者 -> 是历史人物
    (
        [("s", "建立者", "o")],
        "是",
        "{o}是历史人物(创立了{s})",
        "{s}的建立者是{o},能建立政权的人必是历史人物",
    ),
    # 某人发明了某物 -> 是发明家
    (
        [("s", "发明", "o")],
        "是",
        "{s}是发明家(发明了{o})",
        "{s}发明了{o},发明东西的人就是发明家",
    ),
    # 某人是某组织的建立者 -> 是创始人
    (
        [("s", "创立", "o")],
        "是",
        "{s}是创始人(创立了{o})",
        "{s}创立了{o}",
    ),
    # 作品属于某经典集合 -> 是经典作品
    (
        [("s", "属于", "o")],
        "是",
        "{s}是经典作品(属于{o})",
        "{s}属于{o},能入这个集合的都是经典",
    ),
    # 位于某地区 -> 在该地区境内
    (
        [("s", "位于", "o")],
        "在",
        "{s}在{o}境内",
        "{s}位于{o},所以它在{o}境内",
    ),
]

# 触发"著名/出名"这类推断的关系 —— 用户举的例子就是这一类
# 由于内置事实里没有"著名"字段,这里用"可推导的显著性"代替:
# 凡是能当某实体建立者/发明者/首都的地方,都算"重要/有名"
NOTABILITY_TRIGGERS = {
    "建立者": "{s}的建立者{o}是个重要人物",
    "发明": "发明了{o}的{s}是个重要人物",
    "首都": "{s}的首都是{o}",
    "省会": "{s}的省会是{o}",
}


def derive(fact_store, subject: str, rel: str, obj: str) -> List[Tuple[str, str, str]]:
    """
    对一条已知事实做因果/属性推理,返回推出的 (关系, 文本, 依据) 列表。

    fact_store: 需要提供 isa_parents(entity) -> [上位词] 与 has(rel, s, o)
    """
    out: List[Tuple[str, str, str]] = []
    if not subject or not rel or not obj:
        return out

    # --- B. 逆关系 ---
    if rel in INVERSE_RELS:
        inv_rel, tmpl = INVERSE_RELS[rel]
        try:
            text = tmpl.format(s=subject, o=obj)
        except Exception:
            text = ""
        if text:
            out.append((inv_rel, text, f"{subject}{rel}{obj},反过来就是{text}"))

    # --- C. 因果蕴含 ---
    for prems, concl_rel, tmpl, why in CAUSAL_RULES:
        ok = True
        for (ps, prel, po) in prems:
            if prel != rel:
                ok = False
                break
            # 只支持 (s,rel,o) 这种位置,不做更复杂的匹配
            if (ps, po) != ("s", "o"):
                ok = False
                break
        if ok:
            try:
                text = tmpl.format(s=subject, o=obj)
            except Exception:
                text = ""
            if text:
                # 依据里的占位符也要替换掉,否则会显示成字面量 "{s}的建立者是{o}"
                try:
                    why_text = why.format(s=subject, o=obj)
                except Exception:
                    why_text = why
                out.append((concl_rel, text, why_text))

    # --- A. 属性继承(只对"是/属于"做,一层一层往上) ---
    if rel in ISA_RELS:
        seen = {subject}
        cur = obj
        depth = 0
        while cur and depth < 4:
            ups = fact_store.isa_parents(cur) if hasattr(fact_store, "isa_parents") else []
            if not ups:
                break
            for up in ups:
                if up in seen:
                    continue
                seen.add(up)
                out.append(("是", f"{subject}是{up}", f"{subject}是{cur},{cur}是{up}"))
            cur = ups[0]
            depth += 1

    return out
